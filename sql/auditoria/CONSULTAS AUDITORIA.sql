-- A01 · O status da parcela está coerente com a data de vencimento? (RGN003 M4)
SELECT p.ID_PARCELA, p.ID_EMPRESTIMO, p.ID_CLIENTE, p.DATA_VENCIMENTO,
       DATEDIFF(CURDATE(), DATE(p.DATA_VENCIMENTO)) AS DIAS_APOS_VENCIMENTO,
       sp.NOME_STATUS_PARCELA AS STATUS_ATUAL,
       'Parcela vencida que ainda está "A PAGAR"' AS PROBLEMA
FROM PARCELA p JOIN STATUS_PARCELA sp ON sp.ID_STATUS_PARCELA = p.STATUS_PARCELA
WHERE sp.NOME_STATUS_PARCELA = 'A PAGAR' AND DATE(p.DATA_VENCIMENTO) < CURDATE()
UNION ALL
SELECT p.ID_PARCELA, p.ID_EMPRESTIMO, p.ID_CLIENTE, p.DATA_VENCIMENTO,
       DATEDIFF(CURDATE(), DATE(p.DATA_VENCIMENTO)),
       sp.NOME_STATUS_PARCELA,
       'Parcela "EM ATRASO" cujo vencimento ainda não chegou'
FROM PARCELA p JOIN STATUS_PARCELA sp ON sp.ID_STATUS_PARCELA = p.STATUS_PARCELA
WHERE sp.NOME_STATUS_PARCELA = 'EM ATRASO' AND DATE(p.DATA_VENCIMENTO) >= CURDATE()
ORDER BY DIAS_APOS_VENCIMENTO DESC;

-- A02 · Parcela marcada como PAGA sem nenhuma baixa registrada
SELECT p.ID_PARCELA, p.ID_EMPRESTIMO, p.ID_CLIENTE, p.DATA_VENCIMENTO,
       p.VALOR_INICIAL + p.VALOR_JUROS + p.VALOR_MULTA - p.VALOR_DESCONTO AS VALOR_TOTAL,
       'Parcela PAGA sem registro em PARCELA_LANCAMENTO' AS PROBLEMA
FROM PARCELA p
JOIN STATUS_PARCELA sp ON sp.ID_STATUS_PARCELA = p.STATUS_PARCELA
WHERE sp.NOME_STATUS_PARCELA = 'PAGA'
  AND NOT EXISTS (SELECT 1 FROM PARCELA_LANCAMENTO pl WHERE pl.ID_PARCELA = p.ID_PARCELA);

-- A03 · O principal baixado confere com o principal da parcela?
SELECT p.ID_PARCELA, sp.NOME_STATUS_PARCELA AS STATUS_PARCELA,
       p.VALOR_INICIAL                       AS PRINCIPAL_DA_PARCELA,
       SUM(pl.VALOR_INICIAL_PAGO)            AS PRINCIPAL_BAIXADO,
       CASE WHEN SUM(pl.VALOR_INICIAL_PAGO) > p.VALOR_INICIAL + 0.005
                 THEN 'Baixado mais que o principal da parcela'
            WHEN SUM(pl.VALOR_INICIAL_PAGO) < p.VALOR_INICIAL - 0.005 AND sp.NOME_STATUS_PARCELA = 'PAGA'
                 THEN 'Parcela PAGA com principal baixado a menor'
            WHEN SUM(pl.VALOR_INICIAL_PAGO) >= p.VALOR_INICIAL - 0.005
                  AND sp.NOME_STATUS_PARCELA IN ('A PAGAR','EM ATRASO')
                 THEN 'Principal totalmente baixado, mas parcela segue em aberto'
       END AS PROBLEMA
FROM PARCELA p
JOIN STATUS_PARCELA sp      ON sp.ID_STATUS_PARCELA = p.STATUS_PARCELA
JOIN PARCELA_LANCAMENTO pl  ON pl.ID_PARCELA = p.ID_PARCELA
GROUP BY p.ID_PARCELA, p.VALOR_INICIAL, sp.NOME_STATUS_PARCELA
HAVING PROBLEMA IS NOT NULL;

-- A04 · O número de parcelas geradas é igual ao contratado?
SELECT e.ID_EMPRESTIMO, se.NOME_STATUS AS STATUS_EMPRESTIMO,
       e.QTD_PARCELAS AS PARCELAS_CONTRATADAS,
       COUNT(p.ID_PARCELA) AS PARCELAS_GERADAS,
       'Quantidade de parcelas diverge do contratado' AS PROBLEMA
FROM EMPRESTIMO e
JOIN STATUS_EMPRESTIMO se ON se.ID_STATUS_EMPRESTIMO = e.STATUS_EMPRESTIMO
LEFT JOIN PARCELA p       ON p.ID_EMPRESTIMO = e.ID_EMPRESTIMO
WHERE se.NOME_STATUS IN ('PAGO','EM ANDAMENTO','QUITADO','RENEGOCIADO')
GROUP BY e.ID_EMPRESTIMO, se.NOME_STATUS, e.QTD_PARCELAS
HAVING COUNT(p.ID_PARCELA) <> IFNULL(e.QTD_PARCELAS,-1);

-- A05 · Empréstimos em andamento sem contrato, e contratos ativos sem assinatura
SELECT e.ID_EMPRESTIMO, NULL AS ID_CONTRATO, se.NOME_STATUS AS STATUS,
       'Empréstimo liberado/ativo sem contrato vinculado' AS PROBLEMA
FROM EMPRESTIMO e
JOIN STATUS_EMPRESTIMO se ON se.ID_STATUS_EMPRESTIMO = e.STATUS_EMPRESTIMO
WHERE se.NOME_STATUS IN ('AGUARDANDO FINANCEIRO','PAGO','EM ANDAMENTO','QUITADO')
  AND NOT EXISTS (SELECT 1 FROM CONTRATO ct WHERE ct.ID_EMPRESTIMO = e.ID_EMPRESTIMO)
UNION ALL
SELECT ct.ID_EMPRESTIMO, ct.ID_CONTRATO, sc.NOME_STATUS_CONTRATO,
       'Contrato ATIVO sem data de assinatura'
FROM CONTRATO ct
JOIN STATUS_CONTRATO sc ON sc.ID_STATUS_CONTRATO = ct.STATUS_CONTRATO
WHERE sc.NOME_STATUS_CONTRATO = 'ATIVO' AND ct.DATA_ASSINATURA IS NULL;

-- A06 · Consistência da decisão de crédito (RO004 M2, RO009 M2)
WITH base AS (
  SELECT e.*, se.NOME_STATUS AS ST
  FROM EMPRESTIMO e JOIN STATUS_EMPRESTIMO se ON se.ID_STATUS_EMPRESTIMO = e.STATUS_EMPRESTIMO
)
SELECT ID_EMPRESTIMO, ST AS STATUS, 'Decidido, mas sem DATA_DECISAO' AS PROBLEMA FROM base
 WHERE ST IN ('APROVADO','REPROVADO','AGUARDANDO FINANCEIRO','PAGO','EM ANDAMENTO','QUITADO') AND DATA_DECISAO IS NULL
UNION ALL
SELECT ID_EMPRESTIMO, ST, 'Reprovado sem motivo de reprovação' FROM base
 WHERE ST = 'REPROVADO' AND (MOTIVO_REPROVACAO IS NULL OR TRIM(MOTIVO_REPROVACAO) = '')
UNION ALL
SELECT ID_EMPRESTIMO, ST, 'Reprovado com valor aprovado preenchido' FROM base
 WHERE ST = 'REPROVADO' AND IFNULL(VALOR_APROVADO,0) > 0
UNION ALL
SELECT ID_EMPRESTIMO, ST, 'Valor aprovado maior que o solicitado' FROM base
 WHERE VALOR_APROVADO > VALOR_SOLICITADO
UNION ALL
SELECT ID_EMPRESTIMO, ST, 'Desembolso anterior à decisão' FROM base
 WHERE DATA_DESEMBOLSO IS NOT NULL AND DATA_DECISAO IS NOT NULL AND DATA_DESEMBOLSO < DATA_DECISAO
UNION ALL
SELECT ID_EMPRESTIMO, ST, 'Empréstimo liberado sem data de desembolso' FROM base
 WHERE ST IN ('PAGO','EM ANDAMENTO','QUITADO') AND DATA_DESEMBOLSO IS NULL
ORDER BY ID_EMPRESTIMO;

-- A07 · O cliente é o mesmo em empréstimo, parcela e contrato?
SELECT 'PARCELA' AS ORIGEM, p.ID_PARCELA AS ID_REGISTRO, p.ID_EMPRESTIMO,
       p.ID_CLIENTE AS CLIENTE_NO_REGISTRO, e.ID_CLIENTE AS CLIENTE_DO_EMPRESTIMO
FROM PARCELA p JOIN EMPRESTIMO e ON e.ID_EMPRESTIMO = p.ID_EMPRESTIMO
WHERE NOT (p.ID_CLIENTE <=> e.ID_CLIENTE)
UNION ALL
SELECT 'CONTRATO', ct.ID_CONTRATO, ct.ID_EMPRESTIMO, ct.ID_CLIENTE, e.ID_CLIENTE
FROM CONTRATO ct JOIN EMPRESTIMO e ON e.ID_EMPRESTIMO = ct.ID_EMPRESTIMO
WHERE NOT (ct.ID_CLIENTE <=> e.ID_CLIENTE);

-- A08 · Cadastros completos com dados obrigatórios faltando (RF004, RO003 M2)
SELECT x.* FROM (
  SELECT c.ID_CLIENTE, CONCAT(pe.NOME,' ',pe.SOBRENOME) AS CLIENTE, sc.NOME_STATUS AS STATUS_CLIENTE,
         CASE WHEN pe.CPF IS NULL OR pe.CPF NOT REGEXP '^[0-9]{11}$' THEN 'CPF ausente ou inválido'
              WHEN c.RENDA_DECLARADA IS NULL OR c.RENDA_DECLARADA <= 0 THEN 'Renda declarada ausente'
              WHEN c.PROFISSAO IS NULL OR TRIM(c.PROFISSAO) = '' THEN 'Profissão ausente'
         END AS PROBLEMA
  FROM CLIENTE c
  JOIN PESSOA pe          ON pe.ID_PESSOA = c.ID_PESSOA
  LEFT JOIN STATUS_CLIENTE sc ON sc.ID_STATUS_CLIENTE = c.STATUS_CLIENTE
  WHERE IFNULL(sc.NOME_STATUS,'') <> 'POTENCIAL'
) x
WHERE x.PROBLEMA IS NOT NULL;

-- A09 · Possíveis duplicidades de cadastro (RF005)
SELECT 'Pessoas com mesmo nome e data de nascimento' AS VERIFICACAO,
       CONCAT(pe.NOME,' ',pe.SOBRENOME,' / ',pe.DATA_NASC) AS CHAVE,
       COUNT(*) AS QTD, GROUP_CONCAT(pe.ID_PESSOA ORDER BY pe.ID_PESSOA) AS IDS
FROM PESSOA pe
GROUP BY pe.NOME, pe.SOBRENOME, pe.DATA_NASC
HAVING COUNT(*) > 1
UNION ALL
SELECT 'Pessoa com mais de um cadastro de cliente',
       CONCAT('ID_PESSOA ', c.ID_PESSOA), COUNT(*), GROUP_CONCAT(c.ID_CLIENTE ORDER BY c.ID_CLIENTE)
FROM CLIENTE c
GROUP BY c.ID_PESSOA
HAVING COUNT(*) > 1;

-- A10 · A decisão usou um score existente e dentro da validade? (RO007 M2)
SELECT e.ID_EMPRESTIMO, e.ID_CLIENTE, se.NOME_STATUS AS STATUS, e.DATA_DECISAO,
       MAX(cs.DATA_CONSULTA) AS ULTIMA_CONSULTA_ANTES_DA_DECISAO,
       CASE WHEN MAX(cs.DATA_CONSULTA) IS NULL THEN 'Sem consulta de score'
            ELSE 'Score mais antigo que a validade' END AS PROBLEMA
FROM EMPRESTIMO e
JOIN STATUS_EMPRESTIMO se ON se.ID_STATUS_EMPRESTIMO = e.STATUS_EMPRESTIMO
LEFT JOIN CONSULTA_SCORE cs ON cs.ID_CLIENTE = e.ID_CLIENTE
                           AND cs.DATA_CONSULTA <= IFNULL(e.DATA_DECISAO, NOW())
WHERE se.NOME_STATUS IN ('APROVADO','AGUARDANDO FINANCEIRO','PAGO','EM ANDAMENTO','QUITADO','RENEGOCIADO')
GROUP BY e.ID_EMPRESTIMO, e.ID_CLIENTE, se.NOME_STATUS, e.DATA_DECISAO
HAVING MAX(cs.DATA_CONSULTA) IS NULL
    OR DATEDIFF(IFNULL(e.DATA_DECISAO, CURDATE()), MAX(cs.DATA_CONSULTA)) > @validade_score_dias;

-- A11 · A taxa aplicada pertence à faixa do empréstimo e estava vigente? (RO005 M2)
SELECT x.* FROM (
  SELECT e.ID_EMPRESTIMO, e.ID_FAIXA_JUROS AS FAIXA_NO_EMPRESTIMO, t.ID_FAIXA_JUROS AS FAIXA_DA_TAXA,
         t.PERCENTUAL_TAXA, DATE(e.DATA_CADASTRO) AS DATA_EMPRESTIMO,
         t.DATA_INICIO_VIGENCIA, t.DATA_FIM_VIGENCIA,
         CASE WHEN e.ID_FAIXA_JUROS <> t.ID_FAIXA_JUROS THEN 'Taxa pertence a outra faixa de juros'
              WHEN DATE(e.DATA_CADASTRO) < t.DATA_INICIO_VIGENCIA
                OR DATE(e.DATA_CADASTRO) > t.DATA_FIM_VIGENCIA THEN 'Taxa fora da vigência na data do empréstimo'
         END AS PROBLEMA
  FROM EMPRESTIMO e JOIN TAXA_JUROS t ON t.ID_TAXA = e.ID_TAXA_JUROS
) x WHERE x.PROBLEMA IS NOT NULL;

-- A12 · O empréstimo respeita os limites da faixa (prazo máximo e comprometimento da renda)?
-- Premissa: PERCENTUAL_MAX_RENDA está em % (ex.: 30 = 30% da renda). Confirmar com a área de crédito.
SELECT x.* FROM (
  SELECT e.ID_EMPRESTIMO, e.QTD_PARCELAS, f.QTD_PARCELAS_MAX,
         c.RENDA_DECLARADA, f.PERCENTUAL_MAX_RENDA,
         ROUND(100 * mp.MAIOR_PARCELA / NULLIF(c.RENDA_DECLARADA,0), 2) AS COMPROMETIMENTO_RENDA_PERC,
         CASE WHEN e.QTD_PARCELAS > f.QTD_PARCELAS_MAX THEN 'Prazo acima do máximo da faixa'
              WHEN 100 * mp.MAIOR_PARCELA / NULLIF(c.RENDA_DECLARADA,0) > f.PERCENTUAL_MAX_RENDA
                   THEN 'Parcela compromete mais renda que o permitido'
         END AS PROBLEMA
  FROM EMPRESTIMO e
  JOIN FAIXA_JUROS f ON f.ID_FAIXA_JUROS = e.ID_FAIXA_JUROS
  JOIN CLIENTE c     ON c.ID_CLIENTE = e.ID_CLIENTE
  LEFT JOIN (SELECT p.ID_EMPRESTIMO,
                    MAX(p.VALOR_INICIAL + p.VALOR_JUROS) AS MAIOR_PARCELA
             FROM PARCELA p GROUP BY p.ID_EMPRESTIMO) mp ON mp.ID_EMPRESTIMO = e.ID_EMPRESTIMO
) x WHERE x.PROBLEMA IS NOT NULL;

-- A13 · Acordos fora da política de desconto (RO007/RO008 M3, RO003 M4)
SELECT x.* FROM (
  SELECT a.ID_ACORDO, sa.NOME_STATUS_ACORDO AS STATUS_ACORDO,
         ROUND(100 * a.VALOR_DESCONTO / NULLIF(a.VALOR_DIVIDA_BASE,0), 2) AS DESCONTO_PERC,
         IF(a.ID_FUNCIONARIO IS NULL, pd.DESCONTO_MAX_PORTAL, pd.DESCONTO_MAX_FUNCIONARIO) AS LIMITE_APLICAVEL_PERC,
         a.QTD_PARCELAS, pd.PARCELAS_MAX,
         CASE WHEN a.ID_POLITICA IS NULL THEN 'Acordo sem política de desconto vinculada'
              WHEN 100 * a.VALOR_DESCONTO / NULLIF(a.VALOR_DIVIDA_BASE,0)
                   > IF(a.ID_FUNCIONARIO IS NULL, pd.DESCONTO_MAX_PORTAL, pd.DESCONTO_MAX_FUNCIONARIO)
                   THEN 'Desconto acima do limite da política'
              WHEN a.QTD_PARCELAS > pd.PARCELAS_MAX THEN 'Parcelamento acima do máximo da política'
              WHEN DATE(a.DATA_CADASTRO) NOT BETWEEN pd.DATA_VIGENCIA AND pd.DATA_FIM
                   THEN 'Política fora da vigência na data do acordo'
         END AS PROBLEMA
  FROM ACORDO a
  JOIN STATUS_ACORDO sa           ON sa.ID_STATUS_ACORDO = a.STATUS_ACORDO
  LEFT JOIN POLITICA_DESCONTO pd  ON pd.ID_POLITICA_DESC = a.ID_POLITICA
) x WHERE x.PROBLEMA IS NOT NULL;

-- A14 · Contrato renegociado mais de uma vez (RO004 M4: só uma renegociação por contrato)
SELECT a.ID_CONTRATO, COUNT(*) AS QTD_ACORDOS_VALIDOS,
       GROUP_CONCAT(a.ID_ACORDO ORDER BY a.ID_ACORDO) AS ACORDOS
FROM ACORDO a
JOIN STATUS_ACORDO sa ON sa.ID_STATUS_ACORDO = a.STATUS_ACORDO
WHERE a.ID_CONTRATO IS NOT NULL
  AND sa.NOME_STATUS_ACORDO NOT IN ('EM ANALISE','RECUSADO','CANCELADO')
GROUP BY a.ID_CONTRATO
HAVING COUNT(*) > 1;

-- A15 · Lançamentos financeiros com datas e valores incoerentes
WITH base AS (
  SELECT l.*, tp.NOME_TP_LANCAMENTO AS TIPO
  FROM LANCAMENTO l JOIN TP_LANCAMENTO tp ON tp.ID_TP_LANCAMENTO = l.ID_TP_LANCAMENTO
)
SELECT ID_LANCAMENTO, TIPO, VALOR_A_PAGAR, VALOR_PAGO, DATA_PAGTO, DATA_CONCILIACAO,
       'Valor pago sem data de pagamento' AS PROBLEMA
FROM base WHERE VALOR_PAGO > 0 AND DATA_PAGTO IS NULL
UNION ALL
SELECT ID_LANCAMENTO, TIPO, VALOR_A_PAGAR, VALOR_PAGO, DATA_PAGTO, DATA_CONCILIACAO,
       'Data de pagamento com valor pago zerado'
FROM base WHERE DATA_PAGTO IS NOT NULL AND VALOR_PAGO = 0
UNION ALL
SELECT ID_LANCAMENTO, TIPO, VALOR_A_PAGAR, VALOR_PAGO, DATA_PAGTO, DATA_CONCILIACAO,
       'Pago e ainda não conciliado além do prazo'
FROM base WHERE DATA_PAGTO IS NOT NULL AND DATA_CONCILIACAO IS NULL
            AND DATEDIFF(CURDATE(), DATE(DATA_PAGTO)) > @prazo_conciliacao_dias
UNION ALL
SELECT ID_LANCAMENTO, TIPO, VALOR_A_PAGAR, VALOR_PAGO, DATA_PAGTO, DATA_CONCILIACAO,
       'Conta pagadora igual à conta recebedora'
FROM base WHERE ID_CONTA_PAGADOR IS NOT NULL AND ID_CONTA_PAGADOR = ID_CONTA_RECEBEDOR
UNION ALL
SELECT ID_LANCAMENTO, TIPO, VALOR_A_PAGAR, VALOR_PAGO, DATA_PAGTO, DATA_CONCILIACAO,
       'Valor pago maior que o valor a pagar'
FROM base WHERE VALOR_PAGO > VALOR_A_PAGAR
ORDER BY ID_LANCAMENTO;

-- A16 · As baixas de parcelas fecham com o valor do pagamento do cliente?
-- A16-A · Diferença entre o pagamento (LANCAMENTO) e a soma das baixas (PARCELA_LANCAMENTO)
SELECT l.ID_LANCAMENTO, l.VALOR_PAGO AS VALOR_PAGO_NO_LANCAMENTO,
       IFNULL(SUM(pl.VALOR_INICIAL_PAGO + IFNULL(pl.VALOR_JUROS_PAGO,0) + IFNULL(pl.VALOR_MULTA_PAGO,0)
                  - IFNULL(pl.VALOR_DESCONTO,0)),0) AS TOTAL_BAIXADO_NAS_PARCELAS,
       COUNT(pl.ID_PARCELA) AS QTD_BAIXAS
FROM LANCAMENTO l
JOIN TP_LANCAMENTO tp           ON tp.ID_TP_LANCAMENTO = l.ID_TP_LANCAMENTO
LEFT JOIN PARCELA_LANCAMENTO pl ON pl.ID_LANCAMENTO = l.ID_LANCAMENTO
WHERE tp.NOME_TP_LANCAMENTO = 'PAGTO_CLIENTE' AND l.VALOR_PAGO > 0
GROUP BY l.ID_LANCAMENTO, l.VALOR_PAGO
HAVING ABS(l.VALOR_PAGO - IFNULL(SUM(pl.VALOR_INICIAL_PAGO + IFNULL(pl.VALOR_JUROS_PAGO,0)
                                      + IFNULL(pl.VALOR_MULTA_PAGO,0) - IFNULL(pl.VALOR_DESCONTO,0)),0)) > 0.01;

-- A16-B · Baixa duplicada (mesma parcela no mesmo lançamento)
SELECT pl.ID_PARCELA, pl.ID_LANCAMENTO, COUNT(*) AS QTD_BAIXAS_IGUAIS
FROM PARCELA_LANCAMENTO pl
GROUP BY pl.ID_PARCELA, pl.ID_LANCAMENTO
HAVING COUNT(*) > 1;

-- A17 · Regras de juros sobrepostas (faixas de score ou taxas vigentes que se cruzam)
SELECT 'Faixas de score sobrepostas' AS VERIFICACAO, f1.ID_FAIXA_JUROS AS ID_A, f2.ID_FAIXA_JUROS AS ID_B,
       CONCAT(f1.SCORE_MIN,'-',f1.SCORE_MAX,' x ',f2.SCORE_MIN,'-',f2.SCORE_MAX) AS DETALHE
FROM FAIXA_JUROS f1
JOIN FAIXA_JUROS f2 ON f1.ID_FAIXA_JUROS < f2.ID_FAIXA_JUROS
                   AND f1.SCORE_MIN <= f2.SCORE_MAX AND f2.SCORE_MIN <= f1.SCORE_MAX
UNION ALL
SELECT 'Taxas da mesma faixa com vigência sobreposta', t1.ID_TAXA, t2.ID_TAXA,
       CONCAT('Faixa ', t1.ID_FAIXA_JUROS)
FROM TAXA_JUROS t1
JOIN TAXA_JUROS t2 ON t1.ID_FAIXA_JUROS = t2.ID_FAIXA_JUROS AND t1.ID_TAXA < t2.ID_TAXA
                  AND t1.DATA_INICIO_VIGENCIA <= IFNULL(t2.DATA_FIM_VIGENCIA,'9999-12-31')
                  AND t2.DATA_INICIO_VIGENCIA <= IFNULL(t1.DATA_FIM_VIGENCIA,'9999-12-31');

-- A18 · Funcionários com cadastro incompleto (RO001/RO002 M2: acesso depende de cargo, perfil e status)
SELECT x.* FROM (
  SELECT f.ID_MATRICULA, CONCAT(pe.NOME,' ',pe.SOBRENOME) AS FUNCIONARIO, sf.NOME_STATUS AS STATUS_FUNC,
         CASE WHEN f.STATUS_FUNC IS NULL THEN 'Sem status'
              WHEN f.ID_CARGO IS NULL THEN 'Sem cargo'
