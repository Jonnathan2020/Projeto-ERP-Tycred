  LEFT JOIN STATUS_FUNCIONARIO sf  ON sf.ID_STATUS_FUNC = f.STATUS_FUNC
) x WHERE x.PROBLEMA IS NOT NULL;

-- A19 · Clientes ATIVOS que deveriam ser inativados (RGN001 M4)
-- Sem contrato vigente, sem parcela a vencer, sem empréstimo/consulta de score no período.
SELECT c.ID_CLIENTE, CONCAT(pe.NOME,' ',pe.SOBRENOME) AS CLIENTE, c.DATA_CADASTRO,
       'Cliente ATIVO sem vínculo ou movimentação no período de inatividade' AS PROBLEMA
FROM CLIENTE c
JOIN STATUS_CLIENTE sc ON sc.ID_STATUS_CLIENTE = c.STATUS_CLIENTE
JOIN PESSOA pe         ON pe.ID_PESSOA = c.ID_PESSOA
WHERE sc.NOME_STATUS = 'ATIVO'
  AND c.DATA_CADASTRO < DATE_SUB(CURDATE(), INTERVAL @meses_inatividade MONTH)
  AND NOT EXISTS (SELECT 1 FROM CONTRATO ct
                  JOIN STATUS_CONTRATO sct ON sct.ID_STATUS_CONTRATO = ct.STATUS_CONTRATO
                  WHERE ct.ID_CLIENTE = c.ID_CLIENTE AND sct.NOME_STATUS_CONTRATO IN ('ATIVO','PENDENTE'))
  AND NOT EXISTS (SELECT 1 FROM PARCELA p
                  JOIN STATUS_PARCELA sp ON sp.ID_STATUS_PARCELA = p.STATUS_PARCELA
                  WHERE p.ID_CLIENTE = c.ID_CLIENTE
                    AND sp.NOME_STATUS_PARCELA IN ('A PAGAR','EM ATRASO','PARCIALMENTE PAGA'))
  AND NOT EXISTS (SELECT 1 FROM EMPRESTIMO e
                  WHERE e.ID_CLIENTE = c.ID_CLIENTE
                    AND GREATEST(e.DATA_CADASTRO, IFNULL(e.DATA_ULTIMA_ALTERACAO,e.DATA_CADASTRO))
                        >= DATE_SUB(CURDATE(), INTERVAL @meses_inatividade MONTH))
  AND NOT EXISTS (SELECT 1 FROM CONSULTA_SCORE cs
                  WHERE cs.ID_CLIENTE = c.ID_CLIENTE
                    AND cs.DATA_CONSULTA >= DATE_SUB(CURDATE(), INTERVAL @meses_inatividade MONTH));
