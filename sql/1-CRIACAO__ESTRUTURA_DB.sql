-- 1. Criação das Tabelas de Domínio (Precisam existir primeiro)

CREATE TABLE STATUS_ATENDIMENTO (
  ID_STATUS_ATENDIMENTO INT PRIMARY KEY,
  NOME_STATUS CHAR(20) CHECK (NOME_STATUS IN('ABERTO', 'EM ANDAMENTO', 'RESOLVIDO', 'FECHADO', 'CANCELADO'))
);

CREATE TABLE TIPO_ATENDIMENTO (
  ID_TIPO_ATENDIMENTO INT PRIMARY KEY,
  NOME_TIPO CHAR(30) CHECK (NOME_TIPO IN('DUVIDA', 'RECLAMACAO', 'RENEGOCIACAO', 'SOLICITACAO', 'OUTROS'))
);


-- 2. Criação das Tabelas Transacionais

CREATE TABLE ATENDIMENTO (
  ID_ATENDIMENTO INT PRIMARY KEY AUTO_INCREMENT,
  ID_CLIENTE INT NOT NULL,
  ID_FUNCIONARIO_RESP INT,
  ID_TIPO_ATENDIMENTO INT NOT NULL,
  ID_STATUS_ATENDIMENTO INT NOT NULL,
  ID_PARCELA INT,
  ASSUNTO VARCHAR(100) NOT NULL,
  DESCRICAO VARCHAR(500) NOT NULL,
  DATA_ABERTURA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DATA_FECHAMENTO DATETIME,
  FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  FOREIGN KEY (ID_FUNCIONARIO_RESP) REFERENCES FUNCIONARIO(ID_MATRICULA),
  FOREIGN KEY (ID_TIPO_ATENDIMENTO) REFERENCES TIPO_ATENDIMENTO(ID_TIPO_ATENDIMENTO),
  FOREIGN KEY (ID_STATUS_ATENDIMENTO) REFERENCES STATUS_ATENDIMENTO(ID_STATUS_ATENDIMENTO),
  FOREIGN KEY (ID_PARCELA) REFERENCES PARCELA(ID_PARCELA)
);

CREATE TABLE HISTORICO_ATENDIMENTO (
  ID_HISTORICO_ATEND INT PRIMARY KEY AUTO_INCREMENT,
  ID_ATENDIMENTO INT NOT NULL,
  ID_FUNCIONARIO INT NOT NULL,
  DESCRICAO_LOG VARCHAR(500) NOT NULL,
  DATA_REGISTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  FOREIGN KEY (ID_ATENDIMENTO) REFERENCES ATENDIMENTO(ID_ATENDIMENTO),
  FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_MATRICULA)
);

CREATE TABLE AVALIACAO (
  ID_AVALIACAO INT PRIMARY KEY AUTO_INCREMENT,
  ID_ATENDIMENTO INT NOT NULL UNIQUE,
  ID_CLIENTE INT NOT NULL,
  NOTA INT NOT NULL CHECK (NOTA BETWEEN 1 AND 5),
  COMENTARIO VARCHAR(255),
  DATA_AVALIACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  FOREIGN KEY (ID_ATENDIMENTO) REFERENCES ATENDIMENTO(ID_ATENDIMENTO),
  FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE)
);

CREATE TABLE ANEXO_ATENDIMENTO (
  ID_ANEXO INT PRIMARY KEY AUTO_INCREMENT,
  ID_ATENDIMENTO INT NOT NULL,
  ID_HISTORICO_ATEND INT, 
  NOME_ARQUIVO VARCHAR(150) NOT NULL,
  TIPO_EXTENSAO CHAR(5) NOT NULL,
  CAMINHO_ARQUIVO VARCHAR(500) NOT NULL,
  TAMANHO_KB INT,
  DATA_UPLOAD DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  FOREIGN KEY (ID_ATENDIMENTO) REFERENCES ATENDIMENTO(ID_ATENDIMENTO),
  FOREIGN KEY (ID_HISTORICO_ATEND) REFERENCES HISTORICO_ATENDIMENTO(ID_HISTORICO_ATEND)
);
