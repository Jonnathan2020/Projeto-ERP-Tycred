CREATE DATABASE IF NOT EXISTS TYCRED;
USE TYCRED;

-- ==========================================
-- 1. TABELAS INDEPENDENTES (DOMÍNIOS E CADASTROS BASE)
-- ==========================================

CREATE TABLE PESSOA (
  ID_PESSOA INT PRIMARY KEY,
  CPF CHAR(11) UNIQUE,
  NOME CHAR(20) NOT NULL,
  SOBRENOME CHAR(20) NOT NULL,
  SEXO CHAR(1) CHECK (SEXO IN('M','F','O')),
  ESTADO_CIVIL CHAR(15) CHECK (ESTADO_CIVIL IN('SOLTEIRO','SOLTEIRA', 'CASADO','CASADA', 'UNIAO', 'DIVORCIADO', 'DIVORCIADA', 'VIUVO', 'VIUVA')),
  DATA_NASC DATE NOT NULL,
  DATA_CADASTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE EMPRESA (
  ID_EMPRESA INT PRIMARY KEY,
  CNPJ CHAR(14),
  RAZAO_SOCIAL CHAR(50) NOT NULL,
  NOME_FANTASIA CHAR(30)
);

CREATE TABLE STATUS_EMPRESTIMO (
  ID_STATUS_EMPRESTIMO INT PRIMARY KEY,
  NOME_STATUS CHAR(30) CHECK (NOME_STATUS IN('PROPOSTA','EM ANALISE','APROVADO','REPROVADO','AGUARDANDO FINANCEIRO', 'PAGO', 'EM ANDAMENTO', 'RENEGOCIADO', 'QUITADO', 'CANCELADO'))
);

CREATE TABLE STATUS_PARCELA (
  ID_STATUS_PARCELA INT PRIMARY KEY NOT NULL,
  NOME_STATUS_PARCELA CHAR(30) CHECK (NOME_STATUS_PARCELA IN('A PAGAR','EM ATRASO','PAGA','RENEGOCIADA','PARCIALMENTE PAGA'))
);

CREATE TABLE TP_LANCAMENTO (
  ID_TP_LANCAMENTO INT PRIMARY KEY NOT NULL,
  NOME_TP_LANCAMENTO CHAR(30) NOT NULL CHECK (NOME_TP_LANCAMENTO IN ('DESPESA','RECEITA','DESEMBOLSO','SALARIO','PAGTO_CLIENTE','DIVERSOS'))
);

CREATE TABLE FORMA_PAGTO (
  ID_FORMA_PAGTO INT PRIMARY KEY NOT NULL,
  NOME_FORMA_PAGTO CHAR(20) NOT NULL
);

CREATE TABLE HISTORICO_EMPRESTIMO (
  ID_HISTORICO INT PRIMARY KEY NOT NULL,
  DESCRICAO_LOG VARCHAR(100) NOT NULL
);

CREATE TABLE STATUS_CONTRATO (
  ID_STATUS_CONTRATO INT PRIMARY KEY,
  NOME_STATUS_CONTRATO CHAR(20) CHECK (NOME_STATUS_CONTRATO IN('RASCUNHO','PENDENTE','ATIVO','INATIVO','RENEGOCIADO','ENCERRADO'))
);

CREATE TABLE STATUS_ACORDO (
  ID_STATUS_ACORDO INT PRIMARY KEY NOT NULL,
  NOME_STATUS_ACORDO CHAR(30) CHECK (NOME_STATUS_ACORDO IN('EM ANALISE','APROVADO','RECUSADO','CANCELADO', 'CUMPRIDO', 'DESCUMPRIDO'))
);

CREATE TABLE POLITICA_DESCONTO (
  ID_POLITICA_DESC INT PRIMARY KEY NOT NULL,
  DESCRICAO CHAR(50),
  DESCONTO_MAX_PORTAL DECIMAL(7,4) NOT NULL,
  DESCONTO_MAX_FUNCIONARIO DECIMAL(7,4) NOT NULL,
  ENTRADA_MINIMA_PERCENTUAL DECIMAL(7,4) NOT NULL,
  PARCELAS_MAX INT NOT NULL,
  DATA_VIGENCIA DATE NOT NULL,
  DATA_FIM DATE NOT NULL
);

CREATE TABLE FAIXA_JUROS (
  ID_FAIXA_JUROS INT PRIMARY KEY,
  SCORE_MIN INT NOT NULL,
  SCORE_MAX INT NOT NULL,
  QTD_PARCELAS_MAX INT NOT NULL,
  PERCENTUAL_MAX_RENDA DECIMAL(12,2) NOT NULL
);

CREATE TABLE STATUS_CLIENTE (
  ID_STATUS_CLIENTE INT PRIMARY KEY,
  NOME_STATUS CHAR(30) CHECK (NOME_STATUS IN('POTENCIAL', 'ATIVO','INATIVO', 'COMPLETO'))
);

CREATE TABLE STATUS_FUNCIONARIO (
  ID_STATUS_FUNC INT PRIMARY KEY,
  NOME_STATUS CHAR(20) CHECK (NOME_STATUS IN('ATIVO','INATIVO','BLOQUEADO','SUSPENSO'))
);

CREATE TABLE GRUPO_PERM (
  ID_GRUPO_PERM INT PRIMARY KEY,
  NOME_GRUPO CHAR(20),
  MODULO1 TINYINT,
  MODULO2 TINYINT,
  MODULO3 TINYINT,
  MODULO4 TINYINT
);

CREATE TABLE CARGO (
  ID_CARGO INT PRIMARY KEY,
  NOME_CARGO CHAR(20) CHECK (NOME_CARGO IN('ATENDENTE','ANALISTA CREDITO','ANALISTA QUALIDADE','ANALISTA FINANCEIRO','AUXILIAR ADM','ADMINISTRADOR', 'GERENTE', 'SUPERVISOR', 'VENDEDOR'))
);

CREATE TABLE TURNO (
  ID_TURNO INT PRIMARY KEY,
  NOME_TURNO CHAR(10) CHECK (NOME_TURNO IN('MANHA', 'TARDE', 'NOITE', 'MADRUGADA'))
);

CREATE TABLE DEPTO (
  ID_DEPTO INT PRIMARY KEY,
  NOME_DEPTO CHAR(15) CHECK (NOME_DEPTO IN('COMERCIAL','CREDITO','COBRANCA','ATENDIMENTO','FINANCEIRO','JURIDICO'))
);


-- ==========================================
-- 2. TABELAS DE NÍVEL 1 (DEPENDEM APENAS DAS CADASTRAIS)
-- ==========================================

CREATE TABLE USUARIO (
  ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
  ID_PESSOA INT UNIQUE NOT NULL,
  LOGIN VARCHAR(100) UNIQUE NOT NULL,
  SENHA_HASH VARCHAR(255) NOT NULL,
  TIPO_USUARIO CHAR(15) NOT NULL CHECK (TIPO_USUARIO IN('CLIENTE', 'FUNCIONARIO', 'SISTEMA')),
  STATUS_ACESSO CHAR(7) DEFAULT 'ATIVO' CHECK (STATUS_ACESSO IN ('ATIVO', 'INATIVO')),
  DATA_ULTIMO_ACESSO DATETIME,
  CONSTRAINT FK_USUARIO_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA(ID_PESSOA)
);

CREATE TABLE CONTA_BANCARIA (
  ID_CONTA INT PRIMARY KEY AUTO_INCREMENT,
  ID_PESSOA INT NOT NULL,
  BANCO CHAR(3) NOT NULL,
  AGENCIA VARCHAR(10) NOT NULL,
  CONTA VARCHAR(15) NOT NULL,
  TIPO_CONTA CHAR(15) CHECK (TIPO_CONTA IN('CORRENTE', 'POUPANCA')),
  CHAVE_PIX VARCHAR(100),
  CONSTRAINT FK_CONTA_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA(ID_PESSOA)
);

CREATE TABLE TAXA_JUROS (
  ID_TAXA INT PRIMARY KEY,
  ID_FAIXA_JUROS INT NOT NULL,
  PERCENTUAL_TAXA DECIMAL(12,2),
  DATA_INICIO_VIGENCIA DATE,
  DATA_FIM_VIGENCIA DATE,
  CONSTRAINT FK_TAXA_FAIXA FOREIGN KEY (ID_FAIXA_JUROS) REFERENCES FAIXA_JUROS(ID_FAIXA_JUROS)
);

CREATE TABLE FUNCIONARIO (
  ID_MATRICULA INT PRIMARY KEY NOT NULL,
  ID_PESSOA INT NOT NULL,
  PIS CHAR(11),
  CTPS CHAR(20),
  DATA_ADMISSAO DATE,
  ID_TURNO INT,
  ID_DEPTO INT,
  ID_CARGO INT,
  ID_GRUPO_PERMISSAO INT,
  SALARIO_BASE DECIMAL(12,2),
  ID_EMPRESA INT NOT NULL,
  STATUS_FUNC INT,
  CONSTRAINT FK_FUNC_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA(ID_PESSOA),
  CONSTRAINT FK_FUNC_TURNO FOREIGN KEY (ID_TURNO) REFERENCES TURNO(ID_TURNO),
  CONSTRAINT FK_FUNC_DEPTO FOREIGN KEY (ID_DEPTO) REFERENCES DEPTO(ID_DEPTO),
  CONSTRAINT FK_FUNC_CARGO FOREIGN KEY (ID_CARGO) REFERENCES CARGO(ID_CARGO),
  CONSTRAINT FK_FUNC_GRUPO FOREIGN KEY (ID_GRUPO_PERMISSAO) REFERENCES GRUPO_PERM(ID_GRUPO_PERM),
  CONSTRAINT FK_FUNC_EMPRESA FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESA(ID_EMPRESA),
  CONSTRAINT FK_FUNC_STATUS FOREIGN KEY (STATUS_FUNC) REFERENCES STATUS_FUNCIONARIO(ID_STATUS_FUNC)
);


-- ==========================================
-- 3. TABELAS DE NÍVEL 2 E 3 
-- ==========================================

CREATE TABLE CLIENTE (
  ID_CLIENTE INT PRIMARY KEY,
  CNPJ CHAR(14),
  ID_PESSOA INT NOT NULL,
  PROFISSAO CHAR(50),
  RENDA_DECLARADA DECIMAL(12,2),
  COMPROVANTE_RENDA LONGBLOB,
  COMPROVANTE_RESIDENCIA LONGBLOB,
  ID_CONTA INT,
  DATA_CADASTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  STATUS_CLIENTE INT,
  CONSTRAINT FK_CLIENTE_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA(ID_PESSOA),
  CONSTRAINT FK_CLIENTE_CONTA FOREIGN KEY (ID_CONTA) REFERENCES CONTA_BANCARIA(ID_CONTA),
  CONSTRAINT FK_CLIENTE_STATUS FOREIGN KEY (STATUS_CLIENTE) REFERENCES STATUS_CLIENTE(ID_STATUS_CLIENTE)
);

CREATE TABLE LANCAMENTO (
  ID_LANCAMENTO INT PRIMARY KEY NOT NULL,
  DESCRICAO CHAR(30),
  ID_TP_LANCAMENTO INT NOT NULL,
  VALOR_A_PAGAR DECIMAL(12,2) NOT NULL,
  VALOR_PAGO DECIMAL(12,2) NOT NULL,
  ID_FORMA_PAGTO INT,
  LINK_PAGTO VARCHAR(50) NOT NULL,
  ID_CONTA_PAGADOR INT,
  ID_CONTA_RECEBEDOR INT,
  COMPROVANTE_PAGTO VARCHAR(50) NOT NULL,
  DATA_CADASTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DATA_VENCIMENTO DATETIME NOT NULL,
  DATA_PAGTO DATETIME,
  DATA_CONCILIACAO DATETIME,
  CONSTRAINT FK_LANC_TP FOREIGN KEY (ID_TP_LANCAMENTO) REFERENCES TP_LANCAMENTO(ID_TP_LANCAMENTO),
  CONSTRAINT FK_LANC_FORMA FOREIGN KEY (ID_FORMA_PAGTO) REFERENCES FORMA_PAGTO(ID_FORMA_PAGTO),
  CONSTRAINT FK_LANC_CONTA_PAG FOREIGN KEY (ID_CONTA_PAGADOR) REFERENCES CONTA_BANCARIA(ID_CONTA),
  CONSTRAINT FK_LANC_CONTA_REC FOREIGN KEY (ID_CONTA_RECEBEDOR) REFERENCES CONTA_BANCARIA(ID_CONTA)
);

CREATE TABLE EMPRESTIMO (
  ID_EMPRESTIMO INT PRIMARY KEY,
  ID_CLIENTE INT NOT NULL,
  ID_EMPRESA INT NOT NULL,
  ID_FAIXA_JUROS INT NOT NULL,
  ID_TAXA_JUROS INT NOT NULL,
  VALOR_SOLICITADO DECIMAL(12,2),
  VALOR_APROVADO DECIMAL(12,2),
  VALOR_COMISSAO DECIMAL(12,2),
  QTD_PARCELAS INT,
  OBSERVACAO VARCHAR(50),
  STATUS_EMPRESTIMO INT NOT NULL,
  MOTIVO_REPROVACAO CHAR(100),
  ID_HISTORICO_EMPRESTIMO INT,
  DATA_CADASTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DATA_DESEMBOLSO DATETIME,
  DATA_ULTIMA_ALTERACAO DATETIME,
  DATA_DECISAO DATETIME,
  CONSTRAINT FK_EMP_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  CONSTRAINT FK_EMP_EMPRESA FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESA(ID_EMPRESA),
  CONSTRAINT FK_EMP_FAIXA FOREIGN KEY (ID_FAIXA_JUROS) REFERENCES FAIXA_JUROS(ID_FAIXA_JUROS),
  CONSTRAINT FK_EMP_TAXA FOREIGN KEY (ID_TAXA_JUROS) REFERENCES TAXA_JUROS(ID_TAXA),
  CONSTRAINT FK_EMP_STATUS FOREIGN KEY (STATUS_EMPRESTIMO) REFERENCES STATUS_EMPRESTIMO(ID_STATUS_EMPRESTIMO),
  CONSTRAINT FK_EMP_HISTORICO FOREIGN KEY (ID_HISTORICO_EMPRESTIMO) REFERENCES HISTORICO_EMPRESTIMO(ID_HISTORICO)
);

CREATE TABLE CONSULTA_SCORE (
  ID_CONSULTA_SCORE INT PRIMARY KEY NOT NULL,
  ID_CLIENTE INT NOT NULL,
  ID_FUNCIONARIO INT,
  VALOR_SCORE INT NOT NULL,
  DATA_CONSULTA DATETIME NOT NULL,
  DOC_CONSULTA VARCHAR(100),
  QTD_NEGATIVACOES INT,
  QTD_CONSULTAS_RECENTES INT,
  OBSERVACAO CHAR(50),
  CONSTRAINT FK_SCORE_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  CONSTRAINT FK_SCORE_FUNC FOREIGN KEY (ID_FUNCIONARIO) REFERENCES FUNCIONARIO(ID_MATRICULA)
);


