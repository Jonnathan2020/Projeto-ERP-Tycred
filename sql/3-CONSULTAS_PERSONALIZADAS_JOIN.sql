USE TYCRED;

-- ======================================================================
-- CONSULTAS PERSONALIZADAS
-- ======================================================================

SELECT * FROM EMPRESTIMO;
SELECT * FROM PARCELA;
SELECT * FROM LANCAMENTO;

-- 1. CONSULTAR FUNCIONARIOS, DEPARTAMENTO, CARGO E SALARIO
SELECT 
    F.ID_MATRICULA,
    CONCAT(P.NOME, ' ', P.SOBRENOME) AS NOME_FUNCIONARIO,
    D.NOME_DEPTO AS DEPARTAMENTO,
    C.NOME_CARGO AS CARGO,
    F.SALARIO_BASE
FROM FUNCIONARIO F
JOIN PESSOA P ON F.ID_PESSOA = P.ID_PESSOA
JOIN DEPTO D ON F.ID_DEPTO = D.ID_DEPTO
JOIN CARGO C ON F.ID_CARGO = C.ID_CARGO
ORDER BY F.ID_DEPTO, F.ID_CARGO;


-- 2. CONSULTAR USUARIO, LOGIN, TIPO USUARIO E NOME COMPLETO
SELECT 
    U.ID_USUARIO,
    U.LOGIN,
    U.TIPO_USUARIO,
    CONCAT(P.NOME, ' ', P.SOBRENOME) AS NOME_COMPLETO
FROM USUARIO U
JOIN PESSOA P ON U.ID_PESSOA = P.ID_PESSOA
WHERE U.TIPO_USUARIO = 'FUNCIONARIO'
ORDER BY U.ID_USUARIO;


-- 3. CONSULTAR DADOS CLIENTES
SELECT 
    C.ID_CLIENTE,
    CONCAT(P.NOME, ' ', P.SOBRENOME) AS NOME_CLIENTE,
    P.CPF,
    P.DATA_NASC,
    SC.NOME_STATUS AS STATUS_DO_CLIENTE,
    C.RENDA_DECLARADA,
    (SELECT CS.VALOR_SCORE 
     FROM CONSULTA_SCORE CS 
     WHERE CS.ID_CLIENTE = C.ID_CLIENTE 
     ORDER BY CS.DATA_CONSULTA DESC 
     LIMIT 1) AS ULTIMO_SCORE,
    CB.BANCO,
    CB.AGENCIA,
    CB.CONTA
FROM CLIENTE C
INNER JOIN PESSOA P ON C.ID_PESSOA = P.ID_PESSOA
INNER JOIN STATUS_CLIENTE SC ON C.STATUS_CLIENTE = SC.ID_STATUS_CLIENTE
LEFT JOIN CONTA_BANCARIA CB ON C.ID_CONTA = CB.ID_CONTA
ORDER BY P.NOME;


-- 4. CONSULTAR EMPRESTIMO
SELECT 
    E.ID_EMPRESTIMO,
    P.NOME AS CLIENTE,
    EMP.NOME_FANTASIA AS EMPRESA,
    E.VALOR_SOLICITADO,
    E.VALOR_APROVADO,
    E.QTD_PARCELAS,
    FJ.SCORE_MIN,
    FJ.SCORE_MAX,
    TJ.PERCENTUAL_TAXA AS TAXA_JUROS_MENSAL,
    SE.NOME_STATUS AS SITUACAO_EMPRESTIMO,
    E.DATA_CADASTRO AS DATA_CRIACAO,
    E.DATA_DESEMBOLSO
FROM EMPRESTIMO E
INNER JOIN CLIENTE C ON E.ID_CLIENTE = C.ID_CLIENTE
INNER JOIN PESSOA P ON C.ID_PESSOA = P.ID_PESSOA
INNER JOIN EMPRESA EMP ON E.ID_EMPRESA = EMP.ID_EMPRESA
INNER JOIN FAIXA_JUROS FJ ON E.ID_FAIXA_JUROS = FJ.ID_FAIXA_JUROS
INNER JOIN TAXA_JUROS TJ ON E.ID_TAXA_JUROS = TJ.ID_TAXA
INNER JOIN STATUS_EMPRESTIMO SE ON E.STATUS_EMPRESTIMO = SE.ID_STATUS_EMPRESTIMO
ORDER BY E.DATA_CADASTRO DESC;


-- 5. PARCELAS DE UM EMPRESTIMO
SELECT 
    P.ID_PARCELA,
    E.ID_EMPRESTIMO,
    CONCAT(PE.NOME, ' ', PE.SOBRENOME) AS NOME_CLIENTE,
    P.NUMERO_PARCELA,
    P.VALOR_INICIAL,
    P.VALOR_JUROS,
    (P.VALOR_INICIAL + P.VALOR_JUROS + P.VALOR_MULTA - P.VALOR_DESCONTO) AS VALOR_TOTAL_PARCELA,
    P.DATA_VENCIMENTO,
    SP.NOME_STATUS_PARCELA AS STATUS_COBRANCA
FROM PARCELA P
INNER JOIN EMPRESTIMO E ON P.ID_EMPRESTIMO = E.ID_EMPRESTIMO
INNER JOIN CLIENTE C ON P.ID_CLIENTE = C.ID_CLIENTE
INNER JOIN PESSOA PE ON C.ID_PESSOA = PE.ID_PESSOA
INNER JOIN STATUS_PARCELA SP ON P.STATUS_PARCELA = SP.ID_STATUS_PARCELA
ORDER BY P.DATA_VENCIMENTO ASC;


-- 6. FINANCEIRO -> CONCILIACAO LANCAMENTOS
SELECT 
    L.ID_LANCAMENTO,
    L.DESCRICAO,
    TL.NOME_TP_LANCAMENTO AS TIPO_MOVIMENTO,
    L.VALOR_A_PAGAR,
    L.VALOR_PAGO,
    FP.NOME_FORMA_PAGTO AS FORMA_PAGAMENTO,
    CONTA_PAG.NOME AS QUEM_PAGOU,
    CONTA_REC.NOME AS QUEM_RECEBEU,
    L.DATA_VENCIMENTO,
    L.DATA_PAGTO,
    CASE 
        WHEN L.DATA_PAGTO IS NULL THEN 'PENDENTE'
        WHEN L.DATA_CONCILIACAO IS NULL THEN 'PAGO - AGUARDANDO CONCILIAÇÃO'
        ELSE 'CONCILIADO'
    END AS STATUS_CONCILIACAO
FROM LANCAMENTO L
INNER JOIN TP_LANCAMENTO TL ON L.ID_TP_LANCAMENTO = TL.ID_TP_LANCAMENTO
LEFT JOIN FORMA_PAGTO FP ON L.ID_FORMA_PAGTO = FP.ID_FORMA_PAGTO
LEFT JOIN CONTA_BANCARIA CB_PAG ON L.ID_CONTA_PAGADOR = CB_PAG.ID_CONTA
LEFT JOIN PESSOA CONTA_PAG ON CB_PAG.ID_PESSOA = CONTA_PAG.ID_PESSOA
LEFT JOIN CONTA_BANCARIA CB_REC ON L.ID_CONTA_RECEBEDOR = CB_REC.ID_CONTA
LEFT JOIN PESSOA CONTA_REC ON CB_REC.ID_PESSOA = CONTA_REC.ID_PESSOA
ORDER BY L.DATA_VENCIMENTO;


-- 7. DETALHAMENTO DE PARCELA
SELECT 
    PL.ID_PARCELA,
    P.NUMERO_PARCELA,
    PL.ID_LANCAMENTO,
    L.DESCRICAO AS DESCRICAO_LANCAMENTO,
    PL.VALOR_INICIAL_PAGO,
    PL.VALOR_JUROS_PAGO,
    PL.VALOR_MULTA_PAGO,
    PL.DATA_BAIXA
FROM PARCELA_LANCAMENTO PL
INNER JOIN PARCELA P ON PL.ID_PARCELA = P.ID_PARCELA
INNER JOIN LANCAMENTO L ON PL.ID_LANCAMENTO = L.ID_LANCAMENTO
ORDER BY PL.DATA_BAIXA DESC;


-- 8. CONSULTAR COMISSOES
SELECT 
    F.ID_MATRICULA,
    CONCAT(P.NOME, ' ', P.SOBRENOME) AS NOME_FUNCIONARIO,
    C.NOME_CARGO,
    EF.ID_EMPRESTIMO,
    EF.DESCRICAO AS OBSERVACAO_COMISSAO,
    EF.VALOR_COMISSAO,
    E.VALOR_APROVADO AS VALOR_DO_EMPRESTIMO
FROM EMPRESTIMO_FUNCIONARIO EF
INNER JOIN FUNCIONARIO F ON EF.ID_FUNCIONARIO = F.ID_MATRICULA
INNER JOIN PESSOA P ON F.ID_PESSOA = P.ID_PESSOA
INNER JOIN CARGO C ON F.ID_CARGO = C.ID_CARGO
INNER JOIN EMPRESTIMO E ON EF.ID_EMPRESTIMO = E.ID_EMPRESTIMO
ORDER BY EF.VALOR_COMISSAO DESC;


-- 9. CONSULTAR ACORDO RENEGOCIACAO
SELECT 
    A.ID_ACORDO,
    CON.ID_CONTRATO,
    PE.NOME AS NOME_CLIENTE,
    PF.NOME AS FUNCIONARIO_NEGOCIADOR,
    PD.DESCRICAO AS POLITICA_APLICADA,
    A.VALOR_DIVIDA_BASE,
    A.VALOR_DESCONTO,
    A.QTD_PARCELAS,
    A.VALOR_PARCELA,
    SA.NOME_STATUS_ACORDO AS STATUS_DO_ACORDO,
    A.DATA_VALIDADE
FROM ACORDO A
INNER JOIN CONTRATO CON ON A.ID_CONTRATO = CON.ID_CONTRATO
INNER JOIN CLIENTE C ON CON.ID_CLIENTE = C.ID_CLIENTE
INNER JOIN PESSOA PE ON C.ID_PESSOA = PE.ID_PESSOA
INNER JOIN FUNCIONARIO F ON A.ID_FUNCIONARIO = F.ID_MATRICULA
INNER JOIN PESSOA PF ON F.ID_PESSOA = PF.ID_PESSOA
INNER JOIN POLITICA_DESCONTO PD ON A.ID_POLITICA = PD.ID_POLITICA_DESC
INNER JOIN STATUS_ACORDO SA ON A.STATUS_ACORDO = SA.ID_STATUS_ACORDO;